"""Authenticate indirect IFix consumers without dereferencing a VM address.

The twelve load and nine store entries share two complete ordinary Execute
graphs. Loads operate on the preceding slot; stores select the preceding two
slots and ordinarily consume both. Descriptor tags select stack payload,
managed object/value copies, reflected/new/static/storey/chain requests, array
requests, or a raw pointer route. The finite programs preserve each conditional
clear, rebase, clone request and exception continuation. Cpobj reaches the
dispatcher default and is outside this group.

Seven named VM callees are authenticated with their complete finite programs.
stackReferenceToPointer returns the stored non-null pointer plus four, or zero.
pointerValueToAddress accepts Integer (zero-extended), Long, StackReference or
selected managed boxed pointers. Its other object path requests an opaque type
carrier helper and virtual FullName slot, compares the result with the selected
System.Reflection.Pointer literal, then conditionally requests Pointer.Unbox.
That receiver/type/helper outcome remains conditional.

Raw loads read numeric widths with the selected sign/zero extensions and tags.
Raw stores request the selected signed/SSE value reader and write its low bits.
Ldobj/Stobj and reference variants request an unsupported exception on the raw
pointer route and end in INT3; their names establish no raw object copy. Invalid
addresses/slots and unsupported numeric-reader tags have separately proved
exception requests. Hardware SSE state, external EH selection, actual exception
handling and all callee outcomes remain unobserved.

Managed Object/ValueType routes copy twelve bytes and conditionally rebase a
managed index; ValueType routes request cloning. Stable valid slots, indices,
descriptor targets, pointer extent, aliases/overlap, mutable storage and actual
invocation are not proved. Array, reflection, dictionary, storey, ToObject,
PushObject and UpdateReference programs retain their existing catalog owners.
Raw anonymousStoreyInfos framing is not widened. All build anchors are data in
the reviewed contract; code contains only address-free finite grammars.
"""
