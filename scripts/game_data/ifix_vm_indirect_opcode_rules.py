class IndirectOpcodeRuleError(ValueError):
    """A selected indirect declaration lacks its reviewed witness."""


def _need(ok: bool,label: str) -> None:
    if not ok:raise IndirectOpcodeRuleError('indirect-opcodes.'+label)


def _carrier_label(value: Any) -> Any:
    # Older catalog rows use the metadata spelling for elementary carriers.
    return {'System.Object':'object','System.Void':'void','System.String':'string',
            'System.Boolean':'bool','System.Byte':'byte','System.Int32':'int',
            'System.Int64':'long','System.Single':'float','System.Double':'double'}.get(value,value) if type(value) is str else value


def _program(tokens: tuple,at: int,targets: dict[str,int],cells: dict[str,int]) -> bytes:
    p=_Program(at)
    for token in tokens:
        if isinstance(token,str):p.add(token);continue
        kind,*args=token
        if kind=='call':p.call(targets[args[0]])
        elif kind=='rip':p.rip(args[0],cells[args[1]],bytes.fromhex(args[2]))
        elif kind=='branch':
            prefix=bytes.fromhex(args[0]);width=1 if len(prefix)==1 and prefix!=b'\xe9' else 4
            displacement=targets[args[1]]-(at+len(p.raw)+len(prefix)+width)
            p.add(prefix+displacement.to_bytes(width,'little',signed=True))
        else:_need(False,'unknown finite program token')
    return p.finish()


def _claims(spec: dict) -> None:
    _need(all(type(spec.get(k)) is type(v) and spec.get(k)==v for k,v in _BOUNDARIES.items()),'unsupported schema/scope/boundary')
    for key,expected in [('methodRefs',_METHOD_REFS),('helperRefs',_HELPER_REFS),('usageRefs',_USAGE_REFS)]:
        _need(spec.get(key)==expected,'unsupported '+key)
    _need(set(spec.get('rules',{}))==set(_RULES),'indirect family differs')
    for name,expected in _RULES.items():
        row=spec['rules'][name]
        _need(type(row.get('opcodeId')) is int and row.get('entryBlock')==expected[0]
              and type(row.get('stackDeltaSlots')) is int and row['stackDeltaSlots']==expected[1]
              and row.get('rawPointerRoute')==expected[2],'unsupported rule: '+name)
    _need(spec.get('rawLoadRules')==_RAW_LOAD and spec.get('rawStoreRules')==_RAW_STORE,'raw width/tag rules differ')
    _need(set(spec.get('methods',{}))==set(_METHODS)-set(_METHOD_REFS),'own method catalog differs')
    _need(set(spec.get('helpers',{}))=={'typeFromNativeCarrier','intSubtract'},'own helper catalog differs')
    _need(set(spec.get('blocks',{}))==set(_PROGRAMS),'finite block set differs')
    _need(set(spec.get('usageCells',{}))==set(_CELL_TYPES)|set(_OPAQUE)|set(_RUNTIME)|set(_LITERALS),'stored cell set differs')
    _need(spec.get('methodEntryBlocks')==_METHOD_ENTRIES,'method entries differ')
    _need(set(spec.get('virtualMethods',{}))==set(_VIRTUALS),'virtual identity set differs')


def _layouts(image: Any,spec: dict,contract: dict) -> None:
    md=image.metadata;_need(set(spec.get('fieldLayouts',{}))==set(_FIELDS),'field owner set differs')
    for name,fields in _FIELDS.items():
        rows=spec['fieldLayouts'][name];owners=[t for t in md.types if md.type_full_name(t)==name]
        _need(len(owners)==1 and set(rows)==set(fields),'field owner/selection differs: '+name)
        owner=owners[0];offsets=runtime_type_field_offsets(md,image.pe,image.registration,owner.index)
        definitions={md.string(f.name_index):f for f in md.fields_for(owner)}
        for field,(offset,typ) in fields.items():
            row=rows[field];definition=definitions.get(field)
            _need(definition is not None and type(row.get('offset')) is int and row['offset']==offsets.get(field)==offset
                  and row.get('type')==_type(image,definition.type_index)==typ,'named field differs: '+name+'.'+field)
            pointer=image.pe.u64_at_va(_rva(image.registration['types'])+definition.type_index*8)
            _need(not int.from_bytes(image.pe.bytes_at_va(pointer,16)[8:10],'little')&0x10,'static field carrier: '+field)
    value=_ref(contract,'constrainedTypeOperand.stackEffect.valueLayout');owners=[t for t in md.types if md.type_full_name(t)=='IFix.Core.Value']
    _need(value.get('type')=='IFix.Core.Value' and len(owners)==1 and owners[0].bitfield&1,'Value owner differs')
    _need(runtime_type_field_offsets(md,image.pe,image.registration,owners[0].index)==value.get('fieldOffsets')==
          {'Type':16,'Value1':20,'Value2':24},'Value 12-byte layout differs')
    definitions={md.string(f.name_index):f for f in md.fields_for(owners[0])}
    for name,typ in [('Type','IFix.Core.ValueType'),('Value1','int'),('Value2','int')]:
        definition=definitions.get(name)
        _need(definition is not None and _type(image,definition.type_index)==typ,'Value raw carrier differs: '+name)
        pointer=image.pe.u64_at_va(_rva(image.registration['types'])+definition.type_index*8)
        _need(not int.from_bytes(image.pe.bytes_at_va(pointer,16)[8:10],'little')&0x10,'Value static field carrier: '+name)
    tags={r['name']:r['id'] for r in enum_members(md,field_defaults(md),'IFix.Core.ValueType')}
    _need(all(type(tags.get(k)) is int and tags[k]==v for k,v in _TAGS.items()),'descriptor tag enum differs')


def _cells(image: Any,spec: dict,contract: dict,targets: dict[str,int]) -> dict[str,int]:
    result={}
    rows={**spec['usageCells'],**{k:_ref(contract,p) for k,p in _USAGE_REFS.items()}}
    for name,row in rows.items():
        at=_rva(row['cellRva']);result[name]=at
        if name in _RUNTIME:
            _need(set(row)=={'cellRva','identityBoundary'} and row['identityBoundary']=='runtime-init-flag-value-unobserved',
                  'runtime init value promoted: '+name);continue
        raw=image.pe.bytes_at_va(image.pe.image_base+at,8);word=int.from_bytes(raw,'little')
        if 'rawHex' in row:_need(raw==bytes.fromhex(row['rawHex']),'stored usage bytes differ: '+name)
        else:_need(word==_rva(row['encodedWord']),'stored usage word differs: '+name)
        if name=='dictionaryContext':
            definition=_dictionary_usage(image,dict(row,name='instanceDictionary'))
            _dictionary_target(image,definition,targets['dictionaryItem']);continue
        if name in _CELL_TYPES or name in _REF_TYPES:
            tag,typ=(_CELL_TYPES|_REF_TYPES)[name]
            index=unresolved_usage_index(raw,image.registration['typesCount'],tag=tag,source='indirect-opcodes.'+name,offset=at)
            _need(row.get('usageTag',tag)==tag and _type(image,index)==typ,'named non-byref class differs: '+name)
            _need(row.get('identity',row.get('typeName'))==typ,'stored class declaration differs: '+name)
            if 'registeredTypeIndex' in row:_need(type(row['registeredTypeIndex']) is int and row['registeredTypeIndex']==index,'type index differs: '+name)
            if 'rawTypeHex' in row:
                pointer=image.pe.u64_at_va(_rva(image.registration['types'])+index*8)
                _need(image.pe.bytes_at_va(pointer,16).hex()==row['rawTypeHex'],'raw class record differs: '+name)
        elif name in _LITERALS:
            md=image.metadata;table,pool=md.sections['stringLiteral'],md.sections['stringLiteralData']
            index=unresolved_usage_index(raw,table.size//8,tag=5,source='indirect-opcodes.literal',offset=at)
            off=table.offset+index*8;start,size=literal_record(md.buf[off:off+8],pool.size,source='indirect-opcodes.literal',offset=off)
            _need(row.get('usageTag')==5 and row.get('identity')==_LITERALS[name]
                  and row.get('identityBoundary')=='metadata-literal-only'
                  and md.buf[pool.offset+start:pool.offset+start+size]==_LITERALS[name].encode(),'stored pointer literal differs: '+name)
        else:
            _need(row.get('usageTag')==_OPAQUE[name] and row.get('identityBoundary')=='encoded-only'
                  and word<=0xffffffff and word&1 and word>>29==_OPAQUE[name],'opaque usage promoted/malformed: '+name)
    return result


def validate_indirect_opcode_rules(image: Any,spec: dict,body: bytes,body_rva: int,
                                   opcode_ids: dict[str,int],contract: dict,extents: dict[int,int]) -> dict:
    """Authenticate within an already gated image and authenticated Execute."""
    _claims(spec);_layouts(image,spec,contract);targets={}
    for role,identity in _METHODS.items():
        row=_ref(contract,_METHOD_REFS[role]) if role in _METHOD_REFS else spec['methods'][role]
        normalized=dict(row);normalized.setdefault('parameterCount',len(identity[2]))
        _need(type(normalized['parameterCount']) is int,'invalid method parameter count: '+role)
        for key,value in [('returnTypeName',identity[3]),('static',identity[4]),('generic',False)]:
            if key in row:_need(type(row[key]) is type(value) and _carrier_label(row[key])==value,'declared signature differs: '+role)
        if 'returnType' in row:
            declared=row['returnType']
            _need((type(declared) is str and _carrier_label(declared)==identity[3]) or
                  (type(declared) is int and _type(image,declared)==identity[3]),'declared return carrier differs: '+role)
        targets[role]=_identity(image,normalized,identity,role,extents,body_required=role!='stringEqual')
    for role,(identity,slot) in _VIRTUALS.items():
        row=spec['virtualMethods'][role]
        _need(type(row.get('parameterCount')) is int,'invalid virtual parameter count: '+role)
        for key,value in [('returnTypeName',identity[3]),('static',identity[4]),('generic',False)]:
            _need(type(row.get(key)) is type(value) and row[key]==value,'declared virtual signature differs: '+role)
        _identity(image,row,identity,role,extents,virtual_slot=slot,body_required=False)
    for role in set(_HELPER_REFS)|set(spec['helpers']):
        row=_ref(contract,_HELPER_REFS[role]) if role in _HELPER_REFS else spec['helpers'][role]
        count=row['byteCount'];_need(type(count) is int and 0<count<=4096,'invalid helper window: '+role)
        at=_rva(row['rva']);_hash(image.pe.bytes_at_va(image.pe.image_base+at,count),row,'helpers.'+role);targets[role]=at
    _need(spec['helpers']['intSubtract'].get('effectBoundary')=='finite-int32-leaf'
          and spec['helpers']['intSubtract']['byteCount']==5,'subtraction leaf boundary differs')
    _expect(image.pe.bytes_at_va(image.pe.image_base+targets['intSubtract'],5),bytes.fromhex('2bca8bc1c3'),'intSubtract')
    _need(spec['helpers']['typeFromNativeCarrier'].get('effectBoundary')=='opaque-callee-request-only','type-carrier outcome promoted')
    _expect(image.pe.bytes_at_va(image.pe.image_base+targets['subtractSlot'],10),bytes.fromhex('4863c2482bc8488bc1c3'),'subtractSlot')
    for name in ('pcAdvance','loopState','zeroRegister','slotWidth'):
        row=_ref(contract,'basicOpcodeRules.sharedWindows.'+name);at=_rva(row['rva'])
        _hash(_slice(body,body_rva,at,row['byteCount'],name),row,name);targets[name]=at
    _expect(_slice(body,body_rva,targets['zeroRegister'],3,'zeroRegister'),bytes.fromhex('4533ed'),'zeroRegister')
    _expect(_slice(body,body_rva,targets['slotWidth'],5,'slotWidth'),bytes.fromhex('be0c000000'),'slotWidth')
    targets['restorePc']=targets['pcAdvance']-5
    _expect(_slice(body,body_rva,targets['restorePc'],5,'restorePc'),bytes.fromhex('be0c000000'),'restorePc')
    cells=_cells(image,spec,contract,targets)
    wrapper=_Program(targets['dictionaryWrapper']);wrapper.rip('4c8b05',cells['dictionaryContext']);wrapper.rip('e9',targets['dictionaryItem'])
    _expect(image.pe.bytes_at_va(image.pe.image_base+targets['dictionaryWrapper'],12),wrapper.finish(),'dictionaryWrapper')
    targets.update({name:_rva(row['rva']) for name,row in spec['blocks'].items()})
    method_intervals={}
    for role,row in spec['methods'].items():
        count=row.get('bodyBytes',row.get('byteCount'));_need(type(count) is int and count>0,'invalid own method extent: '+role)
        method_intervals[role]=(targets[role],targets[role]+count)
        _need(targets[_METHOD_ENTRIES[role]]==targets[role],'finite method entry differs: '+role)
    coverage={role:[] for role in spec['methods']}
    for name,row in spec['blocks'].items():
        at=targets[name];count=row['byteCount'];_need(type(count) is int and count>0,'invalid block extent: '+name)
        _need(row.get('ownerMethod')==_OWNERS[name] and row.get('next')==_NEXT[name],'block owner/continuation differs: '+name)
        if row['ownerMethod']=='Execute':raw=_slice(body,body_rva,at,count,name)
        else:
            owner=row['ownerMethod'];start,end=method_intervals[owner]
            _need(start<=at and at+count<=end,'block escapes own method: '+name)
            coverage[owner].append((at,at+count));raw=image.pe.bytes_at_va(image.pe.image_base+at,count)
        _hash(raw,row,name);expected=_program(_PROGRAMS[name],at,targets,cells);_expect(raw,expected,'indirect.'+name)
        if _NEXT[name] and _FALLTHROUGH[name]:_need(at+len(expected)==targets[_NEXT[name]],'noncontiguous fallthrough: '+name)
    for role,intervals in coverage.items():
        cursor,end=method_intervals[role]
        for start,stop in sorted(intervals):_need(start==cursor,'incomplete/overlapping method grammar: '+role);cursor=stop
        _need(cursor==end,'incomplete method grammar: '+role)
    actual={r['name']:r['id'] for r in enum_members(image.metadata,field_defaults(image.metadata),'IFix.Core.Code')}
    _need(actual==opcode_ids,'Code enum differs')
    selected={n for n in actual if n.startswith(('Ldind_','Stind_')) or n in ('Ldobj','Stobj')}
    _need(selected==set(spec['rules']),'remaining indirect family differs')
    dispatch=contract['dispatchRules'];extensions=dispatch['extensions'];entries={_rva(r['entryRva']) for r in dispatch['entryPoints']}
    for name,row in spec['rules'].items():
        _need(row['opcodeId']==actual[name],'Code ID differs: '+name)
        entry=resolve_selected_dispatch_entry(body,body_rva,_rva(contract['basicOpcodeRules']['dispatchStartRva']),actual[name],
            zero_compare_rva=_rva(extensions['zeroCompare']['rva']),sub_esi_rva=_rva(extensions['subEsi']['rva']),entry_rvas=entries)
        _need(entry==targets[row['entryBlock']],'selected indirect entry differs: '+name)
    return dict(status='validated_conditional_indirect_opcode_rules',ruleCount=len(spec['rules']),finiteBlockCount=len(_PROGRAMS),
                ownedMethodCount=len(spec['methods']),rules=project_indirect_opcode_rules(None,spec),evidenceBoundary='conditional',
                executionBoundary='unobserved',rawPointerBoundary=spec['rawPointerBoundary'],normalReturnBoundary=spec['normalReturnBoundary'])


def project_indirect_opcode_rules(instructions: list[dict]|None,spec: dict) -> list[dict]:
    """Project selected authored rows; never read memory or simulate a callee."""
    _claims(spec);result=[]
    selected=[dict(opcode=name,**row) for name,row in spec['rules'].items()] if instructions is None else instructions
    for instruction in selected:
        name=instruction.get('opcode')
        if name not in spec['rules']:continue
        row=spec['rules'][name]
        _need(type(instruction.get('opcodeId')) is int and instruction['opcodeId']==row['opcodeId'],'authored Code ID differs: '+name)
        if instructions is not None:
            operand=instruction.get('operand');_need(type(operand) is int and 0<=operand<=0xffffffff,'invalid authored Int32 operand: '+name)
            signed=operand if operand<0x80000000 else operand-0x100000000
            if 'operandSigned' in instruction:_need(type(instruction['operandSigned']) is int and instruction['operandSigned']==signed,'inconsistent signed operand: '+name)
        result.append(dict(opcode=name,opcodeId=row['opcodeId'],normalTopDelta=row['stackDeltaSlots'],rawPointerRoute=row['rawPointerRoute'],
            rawLoad=spec['rawLoadRules'].get(name),rawStore=spec['rawStoreRules'].get(name),evidenceBoundary='conditional',executionBoundary='unobserved',
            normalReturnBoundary=spec['normalReturnBoundary'],rawPointerBoundary=spec['rawPointerBoundary']))
    return result


def validate_selected_indirect_opcode_rules(contract: dict,*,gameassembly: Path|None,metadata: Path|None,spec: dict|None=None) -> dict:
    """Gate explicit selected inputs before opening an image or emitting rows."""
    if gameassembly is None or metadata is None:return dict(status='missing',detail='explicit GameAssembly.dll and metadata paths are required',rules=[])
    inputs=contract['nativeInputs'];gate=check_installed_native_inputs(inputs['gameAssemblySha256'],inputs['globalMetadataSha256'],gameassembly=Path(gameassembly),metadata=Path(metadata))
    if gate.status!='validated':return dict(status=gate.status,detail=gate.detail,rules=[])
    image=NativeImage(gate.gameassembly,gate.metadata,label='ifix.indirect-opcodes');extents=image.mapper.pdata_function_extents(image.pe)
    at=_identity(image,contract['consumer'],('IFix.Core.VirtualMachine','Execute',_EXECUTE_TYPES,'IFix.Core.Value*',False),'Execute',extents)
    body=image.pe.bytes_at_va(image.pe.image_base+at,contract['consumer']['bodyBytes'])
    ids={r['name']:r['id'] for r in enum_members(image.metadata,field_defaults(image.metadata),'IFix.Core.Code')}
    return validate_indirect_opcode_rules(image,spec if spec is not None else contract['indirectOpcodeRules'],body,at,ids,contract,extents)


