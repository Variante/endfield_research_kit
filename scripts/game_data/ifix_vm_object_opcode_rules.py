class ObjectOpcodeRuleError(ValueError):
    """A selected object/type declaration lacks its reviewed witness."""


def _need(ok: bool, detail: str) -> None:
    if not ok: raise ObjectOpcodeRuleError('object-opcodes.'+detail)


def _claims(spec: dict) -> None:
    _need(all(type(spec.get(k)) is type(v) and spec.get(k)==v for k,v in _CLAIMS.items()),'unsupported schema/reference/boundary')
    _need(set(spec['rules'])==set(_RULES),'object/type rule set differs')
    for name,wanted in _RULES.items():
        row=spec['rules'][name]
        _need(type(row.get('opcodeId')) is int and all(type(row.get(k)) is type(v) and row.get(k)==v for k,v in wanted.items()),'rule recipe differs: '+name)
    _need(set(spec['methods'])==set(_METHODS)-set(_CLAIMS['methodRefs']),'owned method set differs')
    _need(set(spec['virtualMethods'])==set(_VIRTUALS),'virtual method set differs')
    _need(set(spec['helpers'])=={'assignableRequest','typeHandleRequest'},'owned helper set differs')
    _need(set(spec['blocks'])==set(_PROGRAMS),'finite graph block set differs')
    _need(set(spec['usageCells'])==(set(_CELL_TYPES)|set(_LITERALS)|set(_OPAQUE_CELLS)|set(_DATA_CELLS))-set(_CLAIMS['usageRefs']), 'stored cell set differs')


def _carrier(image: Any, pointer: int, expected: str, seen: frozenset[int] = frozenset()) -> None:
    _need(len(seen)<8 and pointer not in seen,'named carrier: recursive/deep type')
    raw=image.pe.bytes_at_va(pointer,16)
    _need(len(raw)==16 and not raw[11]&0x20,'named carrier: malformed/by-reference type')
    nested=expected.endswith('[]') or expected.endswith('*')
    kind=(0x1d if expected.endswith('[]') else 0x0f) if nested else _KINDS.get(expected,0x12)
    _need(raw[10]==kind,'named carrier: kind differs: '+expected)
    if nested:_carrier(image,int.from_bytes(raw[:8],'little'),expected[:-2] if expected.endswith('[]') else expected[:-1],seen|{pointer})


def _signature(image: Any, identity: tuple) -> None:
    owner,name,params,returned,static=identity;md=image.metadata
    matches=[m for t in md.types if md.type_full_name(t)==owner for m in md.methods_for(t)
             if md.string(m.name_index)==name and m.parameter_count==len(params)
             and [_type(image,p.type_index) for p in md.parameters_for(m)]==params]
    _need(len(matches)==1,'named overload differs: '+owner+'.'+name);m=matches[0]
    for index,typ in [(p.type_index,t)for p,t in zip(md.parameters_for(m),params)]+[(m.return_type,returned)]:
        _carrier(image,image.pe.u64_at_va(_rva(image.registration['types'])+index*8),typ)


def _method_declaration(row: dict, identity: tuple, *, virtual: bool=False) -> None:
    _need(type(row.get('parameterCount')) is int,'declared parameter count differs')
    if virtual:_need(type(row.get('virtualSlot')) is int and row['virtualSlot']==identity[5],'declared virtual slot differs')
    for key,value in [('returnTypeName',identity[3]),('static',identity[4]),('generic',False)]:
        if virtual or key in row:_need(type(row.get(key)) is type(value) and row.get(key)==value,'declared method identity differs: '+key)


def _cell_declaration(row: dict, identity: str, index: int|None=None, raw_type: bytes|None=None) -> None:
    for key in ('identity','typeName'):
        if key in row:_need(row[key]==identity,'declared cell identity differs')
    if index is not None and 'registeredTypeIndex'in row:_need(type(row['registeredTypeIndex']) is int and row['registeredTypeIndex']==index,'declared type index differs')
    if raw_type is not None and 'rawTypeHex'in row:_need(raw_type==bytes.fromhex(row['rawTypeHex']),'declared raw type differs')


def _cells(image: Any,spec: dict,contract: dict) -> dict[str,int]:
    rows=dict(spec['usageCells']);rows.update({n:_ref(contract,p)for n,p in _CLAIMS['usageRefs'].items()});result={}
    for name,row in rows.items():
        at=_rva(row['cellRva']);size=4 if name in _DATA_CELLS else 8;raw=image.pe.bytes_at_va(image.pe.image_base+at,size);result[name]=at
        declared=row.get('rawHex',row.get('hex'))
        if declared is None:declared=_rva(row['encodedWord']).to_bytes(size,'little').hex()
        _need(raw==bytes.fromhex(declared),'stored cell bytes differ: '+name)
        if name in _DATA_CELLS:
            _need(raw.hex()==_DATA_CELLS[name],'stored data differs: '+name);continue
        if name in _CELL_TYPES:
            tag,typ=_CELL_TYPES[name]
            _need(all(type(row[key]) is int and row[key]==tag for key in ('usageTag','tag')if key in row)
                  and (name in _CLAIMS['usageRefs'] or 'usageTag'in row),'type usage tag differs: '+name)
            index=unresolved_usage_index(raw,image.registration['typesCount'],tag=tag,source='object-opcodes.'+name,offset=at)
            pointer=image.pe.u64_at_va(_rva(image.registration['types'])+index*8);_carrier(image,pointer,typ)
            _need(runtime_type_name(image.pe,image.metadata,pointer)==typ,'named usage carrier differs: '+name)
            _cell_declaration(row,typ,index,image.pe.bytes_at_va(pointer,16))
        elif name in _LITERALS:
            md=image.metadata;table,pool=md.sections['stringLiteral'],md.sections['stringLiteralData']
            index=unresolved_usage_index(raw,table.size//8,tag=5,source='object-opcodes.literal',offset=at);off=table.offset+index*8
            start,count=literal_record(md.buf[off:off+8],pool.size,source='object-opcodes.literal',offset=off)
            _need(md.buf[pool.offset+start:pool.offset+start+count]==_LITERALS[name].encode(),'literal bytes differ: '+name)
            _cell_declaration(row,_LITERALS[name])
        else:
            tag=_OPAQUE_CELLS[name];_need(row.get('usageTag')==tag and row.get('identityBoundary')=='encoded-only','opaque cell boundary differs: '+name)
            unresolved_usage_index(raw,len(image.metadata.methods),tag=tag,source='object-opcodes.context',offset=at)
    return result


def _program(tokens: tuple, at: int, targets: dict[str,int], cells: dict[str,int]) -> bytes:
    p=_Program(at)
    for token in tokens:
        if isinstance(token,str):p.add(token);continue
        kind,*args=token
        if kind=='call':p.call(targets[args[0]])
        elif kind=='rip':p.rip(args[0],cells[args[1]])
        elif kind=='branch':
            prefix=bytes.fromhex(args[0]);width=1 if len(prefix)==1 and prefix!=b'\xe9' else 4
            delta=targets[args[1]]-(at+len(p.raw)+len(prefix)+width)
            p.add(prefix+delta.to_bytes(width,'little',signed=True))
        else:_need(False,'unknown finite program token')
    return p.finish()


def validate_object_opcode_rules(image: Any,spec: dict,body: bytes,body_rva: int,opcode_ids: dict[str,int],contract: dict,extents: dict[int,int]) -> dict:
    """Authenticate within the caller's gated image and complete Execute body."""
    _claims(spec);_value_layout(image,contract);_anonymous_layout(image,contract['anonymousStoreyRules']);targets={}
    for role,identity in _METHODS.items():
        row=_ref(contract,_CLAIMS['methodRefs'][role]) if role in _CLAIMS['methodRefs'] else spec['methods'][role]
        normalized=dict(row);normalized.setdefault('parameterCount',len(identity[2]));_signature(image,identity)
        _method_declaration(normalized,identity)
        if role in _CLAIMS['methodRefs'] and 'byteCount'in row:normalized.setdefault('bodyBoundary','entry-window-callee-outcome-unresolved')
        targets[role]=_identity(image,normalized,identity,role,extents,body_required=False)
    for role,identity in _VIRTUALS.items():
        row=spec['virtualMethods'][role]
        _method_declaration(row,identity,virtual=True)
        _signature(image,identity[:5]);_identity(image,row,identity[:5],role,extents,virtual_slot=identity[5])
    for role in set(_CLAIMS['helperRefs'])|set(spec['helpers']):
        row=_ref(contract,_CLAIMS['helperRefs'][role])if role in _CLAIMS['helperRefs']else spec['helpers'][role]
        count=row['byteCount'];_need(type(count) is int and 0<count<=4096,'invalid helper window: '+role);at=_rva(row['rva'])
        _hash(image.pe.bytes_at_va(image.pe.image_base+at,count),row,'helper.'+role);targets[role]=at
        if role in spec['helpers']:
            _need(row.get('effectBoundary')=='selected-vtable-prefix-runtime-dispatch-unobserved','helper boundary promoted: '+role)
    for role,tokens in _PREFIXES.items():
        row=spec['helpers'][role];expected=_program(tokens,targets[role],targets,{})
        _need(row['byteCount']==len(expected),'vtable prefix length differs: '+role)
        _expect(image.pe.bytes_at_va(image.pe.image_base+targets[role],len(expected)),expected,'prefix.'+role)
    _expect(image.pe.bytes_at_va(image.pe.image_base+targets['pointerSize'],6),bytes.fromhex('b808000000c3'),'pointer size leaf')
    _expect(image.pe.bytes_at_va(image.pe.image_base+targets['isPrimitive'],13),_program(('488bd1b95f000000',('branch','e9','typePredicate')),targets['isPrimitive'],targets,{}),'primitive predicate wrapper')
    _need(spec['methods']['marshalSize']['byteCount']==5,'Marshal entry window differs')
    targets['marshalRuntimeRequest']=_rva(spec['methods']['marshalSize']['jumpTargetRva'])
    _expect(image.pe.bytes_at_va(image.pe.image_base+targets['marshalSize'],5),_program((('branch','e9','marshalRuntimeRequest'),),targets['marshalSize'],targets,{}),'Marshal request thunk')
    _expect(image.pe.bytes_at_va(image.pe.image_base+targets['throwStop'],20),bytes.fromhex('4883ec2833c04889413848894140e87d030000cc'),'stop wrapper')
    for role,path in _CLAIMS['tailRefs'].items():
        row=_ref(contract,path);at=_rva(row['rva']);_hash(_slice(body,body_rva,at,row['byteCount'],role),row,role);targets[role]=at
    targets['restorePc']=targets['pcAdvance']-5;_expect(_slice(body,body_rva,targets['restorePc'],5,'restorePc'),bytes.fromhex('be0c000000'),'restorePc')
    cells=_cells(image,spec,contract);targets.update({n:_rva(r['rva'])for n,r in spec['blocks'].items()})
    for name,row in spec['blocks'].items():
        at=targets[name];raw=_slice(body,body_rva,at,row['byteCount'],name);_hash(raw,row,name);expected=_program(_PROGRAMS[name],at,targets,cells);_expect(raw,expected,name)
        _need(row.get('next')==_NEXT[name],'graph continuation differs: '+name)
        if _FALLTHROUGH[name]:_need(_NEXT[name] is not None and at+len(expected)==targets[_NEXT[name]],'noncontiguous graph fallthrough: '+name)
    actual={r['name']:r['id']for r in enum_members(image.metadata,field_defaults(image.metadata),'IFix.Core.Code')};_need(actual==opcode_ids,'Code enum differs')
    tags={r['name']:r['id']for r in enum_members(image.metadata,field_defaults(image.metadata),'IFix.Core.ValueType')}
    _need(all(tags.get(k)==v for k,v in {'Integer':0,'Long':1,'Float':2,'Double':3,'Object':8,'ValueType':9}.items()),'selected Value tags differ')
    dispatch=contract['dispatchRules'];ex=dispatch['extensions'];entries={_rva(r['entryRva'])for r in dispatch['entryPoints']}
    for name,row in spec['rules'].items():
        _need(row['opcodeId']==actual[name],'Code ID differs: '+name)
        entry=resolve_selected_dispatch_entry(body,body_rva,_rva(contract['basicOpcodeRules']['dispatchStartRva']),actual[name],zero_compare_rva=_rva(ex['zeroCompare']['rva']),sub_esi_rva=_rva(ex['subEsi']['rva']),entry_rvas=entries)
        _need(entry==targets[row['entryBlock']],'selected object entry differs: '+name)
    return dict(status='validated_conditional_object_opcode_rules',ruleCount=len(_RULES),finiteBlockCount=len(_PROGRAMS),rules=project_object_opcode_rules(None,spec),evidenceBoundary='conditional',executionBoundary='unobserved')


def project_object_opcode_rules(instructions: list[dict]|None,spec: dict) -> list[dict]:
    """Expose authored Type selectors and recipes without choosing runtime paths."""
    _claims(spec);result=[];selected=[dict(opcode=n,**r)for n,r in spec['rules'].items()]if instructions is None else instructions
    for ins in selected:
        name=ins.get('opcode')
        if name not in _RULES:continue
        row=spec['rules'][name];_need(type(ins.get('opcodeId')) is int and ins['opcodeId']==row['opcodeId'],'opcode ID differs: '+name)
        extra={}
        if instructions is not None:
            operand=ins.get('operand');_need(type(operand) is int and 0<=operand<=0xffffffff,'invalid authored Int32 operand: '+name)
            signed=operand if operand<0x80000000 else operand-0x100000000
            _need('operandSigned'not in ins or type(ins['operandSigned']) is int and ins['operandSigned']==signed,'inconsistent signed operand: '+name)
            extra=dict(operandUnsigned=operand,operandSigned=signed,externTypeIndex=signed if signed>=0 or name in ('Sizeof','Ldtoken','Ldtype')else None,anonymousInfoIndex=~signed if signed<0 and name in ('Isinst','Castclass')else None)
        result.append(dict(opcode=name,opcodeId=row['opcodeId'],**extra,**_RULES[name],normalNextInstructionDelta=1,runtimeResult='unobserved',evidenceBoundary='conditional',executionBoundary='unobserved',**{k:spec[k]for k in ('calleeBoundary','storageBoundary','exceptionBoundary','anonymousBoundary','managedBoundary')}))
    return result


def validate_selected_object_opcode_rules(contract: dict,*,gameassembly: Path,metadata: Path,spec: dict|None=None) -> dict:
    """Gate explicit selected paths before opening an image; never infer a root."""
    if gameassembly is None or metadata is None:return dict(status='missing',evidenceBoundary='unresolved',detail='explicit native paths required')
    inputs=contract['nativeInputs'];_need(bool(inputs.get('gameAssemblySha256'))and bool(inputs.get('globalMetadataSha256')),'native hashes required')
    gate=check_installed_native_inputs(inputs['gameAssemblySha256'],inputs['globalMetadataSha256'],gameassembly=Path(gameassembly),metadata=Path(metadata))
    if gate.status!='validated':return dict(status=gate.status,evidenceBoundary='unresolved',detail=gate.detail)
    image=NativeImage(gate.gameassembly,gate.metadata,label='ifix.object-opcodes');extents=image.mapper.pdata_function_extents(image.pe)
    at=_identity(image,contract['consumer'],('IFix.Core.VirtualMachine','Execute',_EXECUTE_TYPES,'IFix.Core.Value*',False),'Execute',extents)
    body=image.pe.bytes_at_va(image.pe.image_base+at,contract['consumer']['bodyBytes']);ids={r['name']:r['id']for r in enum_members(image.metadata,field_defaults(image.metadata),'IFix.Core.Code')}
    return validate_object_opcode_rules(image,contract['objectOpcodeRules']if spec is None else spec,body,at,ids,contract,extents)


