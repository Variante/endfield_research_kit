"""Authenticate selected type/object opcode caller programs without execution.

Sizeof chooses the pointer-size leaf or Marshal.SizeOf after the Type value
predicate. Ldtoken requests the named TypeHandle virtual slot, boxes its returned
carrier, and forwards the RuntimeTypeHandle Type to PushObject. Ldtype forwards
the selected Type object with System.Type. Their normal top delta is one.

Isinst rewrites its slot as Object at the physical base-relative managed index.
It requests assignability, stores a candidate or null, and applies the negative
operand AnonymousStorey Slots compatibility program. Castclass leaves a normal
slot unchanged, with null accepted and failed compatibility requesting an
InvalidCastException stop. Neither caller proves a source managed tag.

Box has native Integer/Long Type choices, primitive Float/Double boxing and
Object/ValueType index retention. Negative operands retag Object directly;
unsupported tags request a runtime exception and retag only on normal return.
Unbox and Unbox_Any share one entry: negative operands and non-Object tags have
no explicit conversion; selected reference Types check non-null assignability;
selected value Types reject null, retag nonprimitive/nonenum values, or forward
the selected/enum-underlying Type to UnboxPrimitive. Caller graphs preserve these
requests without imposing CLR behavior from the opcode names.

The common Type query prefixes prove slot-based pointer/MethodInfo selection.
Concrete runtime implementation selection, API/helper outcomes, live storage,
aliasing, exception transfer and execution remain unobserved. The parent owns
the authenticated loader table order and dependency groups. All native addresses
and hashes are read from the reviewed contract.
"""
