"""Authenticate the selected remaining Conv_* programs without executing IFix.

All thirty-two remaining Conv entries are selected through the separately
validated finite dispatcher. Their complete ordinary control graphs are checked
against relocatable instruction grammars, including unsupported tags, selected
overflow requests, and normal-return continuation of throwRuntimeException.
Conv_I8 remains in its existing owner. Conversion uses the preceding 12-byte
slot and has no ordinary top delta. The resolver's mutations and callees' actual
results retain their separately documented conditions.

Unsigned/native conversions can first request tryConvertStackReferenceToPointer.
Its selected finite leaf changes StackReference to Long, stores the non-null
stored pointer plus four (zero for null), and returns true; otherwise it returns
false. That true path bypasses numeric conversion. This is a payload-address
rule, with valid/stable storage and pointer arithmetic still conditional.

Narrow signed conversions select low8/low16 and sign extension; unsigned ones
select zero extension. These programs do not inherit CLR range semantics from
their names. Checked aliases share native entries and sometimes test the actual
opcode. Their authenticated comparisons and conditional SSE helpers are recorded
as native programs. In particular, upper-bound guards do not establish a CLR
lower-bound check. Some unsupported tags reach zero stores; other paths request
runtime exceptions. Conv_R_Un retags non-Integer/Long payloads as Double without
a conversion store. The validator does not simulate arbitrary floats or VM code.

Named metadata carriers reject byref, wrong return/static/generic signatures,
or a changed registered pointer. Float constants are authenticated as data and
complete small helper programs are checked separately. SSE rounding, exception
masks, NaN outcomes, caller state, runtime sharing, opaque allocation/boxing/
exception outcomes, external EH selection, aliasing and actual invocation remain
unobserved. No raw patch framing or anonymous-storey file-table join is widened.
Addresses and hashes live only in the reviewed contract, never this module.
"""
