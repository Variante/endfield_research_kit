class ConversionOpcodeRuleError(ValueError):
    """A selected conversion declaration lacks its reviewed witness."""


def _need(ok: bool, label: str) -> None:
    if not ok: raise ConversionOpcodeRuleError('conversion-opcodes.'+label)


def _program(tokens: tuple, at: int, targets: dict[str,int], cells: dict[str,int]) -> bytes:
    p=_Program(at)
    for token in tokens:
        if isinstance(token,str): p.add(token); continue
        kind,*args=token
        if kind=='call': p.call(targets[args[0]])
        elif kind=='rip': p.rip(args[0],cells[args[1]])
        elif kind=='branch':
            prefix=bytes.fromhex(args[0]);target=targets[args[1]]
            width=1 if len(prefix)==1 and prefix!=b'\xe9' else 4
            # EB/Jcc short displacements and E9/0F Jcc near displacements.
            if prefix==b'\xe9': width=4
            displacement=target-(at+len(p.raw)+len(prefix)+width)
            p.add(prefix+displacement.to_bytes(width,'little',signed=True))
        else: _need(False,'unknown finite program token')
    return p.finish()


def _claims(spec: dict) -> None:
    _need(all(type(spec.get(k)) is type(v) and spec.get(k)==v for k,v in _BOUNDARIES.items()),'unsupported schema/scope/boundary')
    for key,expected in [('methodRefs',_METHOD_REFS),('helperRefs',_HELPER_REFS),('tailRefs',_TAIL_REFS)]:
        _need(spec.get(key)==expected,'unsupported '+key)
    _need(set(spec.get('rules',{}))==set(_RULE_PROGRAMS),'remaining conversion family differs')
    for name,entry in _RULE_PROGRAMS.items():
        row=spec['rules'][name]
        _need(type(row.get('opcodeId')) is int and row.get('entryBlock')==entry
              and type(row.get('normalTopDelta')) is int and row['normalTopDelta']==0
              and row.get('normalResultBoundary')=='conditional-native-numeric-or-pointer-route'
              and row.get('floatBoundary')=='selected-SSE-program-hardware-state-unobserved','unsupported rule: '+name)
    _need(set(spec.get('methods',{}))==set(_METHODS)-set(_METHOD_REFS),'own method catalog differs')
    _need(set(spec.get('helpers',{}))==set(_LEAF_PROGRAMS)-{'tryPointer','nativePointerSize'}|{'overflowRequest'},'own helper catalog differs')
    _need(set(spec.get('blocks',{}))==set(_PROGRAMS),'finite graph block set differs')
    _need(set(spec.get('usageCells',{}))==set(_CELL_TYPES)|set(_DATA_VALUES)|set(_OPAQUE_CELLS),'stored conversion cell set differs')


def _value_layout(image: Any,contract: dict) -> None:
    row=_ref(contract,'constrainedTypeOperand.stackEffect.valueLayout');md=image.metadata
    owners=[t for t in md.types if md.type_full_name(t)=='IFix.Core.Value']
    _need(len(owners)==1 and owners[0].bitfield&1 and row.get('type')=='IFix.Core.Value','Value owner differs')
    fields={'Type':('IFix.Core.ValueType',16),'Value1':('int',20),'Value2':('int',24)}
    _need(runtime_type_field_offsets(md,image.pe,image.registration,owners[0].index)==row.get('fieldOffsets')==
          {k:v[1] for k,v in fields.items()},'Value 12-byte layout differs')
    definitions={md.string(f.name_index):f for f in md.fields_for(owners[0])}
    for name,(typ,_) in fields.items():
        definition=definitions.get(name)
        _need(definition is not None and _type(image,definition.type_index)==typ,'Value raw carrier differs: '+name)
        pointer=image.pe.u64_at_va(_rva(image.registration['types'])+definition.type_index*8)
        _need(not int.from_bytes(image.pe.bytes_at_va(pointer,16)[8:10],'little')&0x10,'Value static field carrier: '+name)
    tags={r['name']:r['id'] for r in enum_members(md,field_defaults(md),'IFix.Core.ValueType')}
    _need(all(type(tags.get(k)) is int and tags[k]==v for k,v in
              {'Integer':0,'Long':1,'Float':2,'Double':3,'StackReference':4}.items()),'numeric/pointer tag enum differs')


def _cells(image: Any,spec: dict) -> dict[str,int]:
    result={}
    for name,row in spec['usageCells'].items():
        at=_rva(row['cellRva']);size=row['byteCount']
        _need(type(size) is int and size in (4,8),'invalid stored cell size: '+name)
        raw=image.pe.bytes_at_va(image.pe.image_base+at,size);_hash(raw,row,'cells.'+name);result[name]=at
        if name in _DATA_VALUES:
            size,value=_DATA_VALUES[name];expected=struct.pack('<f' if size==4 else '<d',value)
            _need(raw==expected and row.get('value')==value,'native numeric constant differs: '+name)
        elif name in _CELL_TYPES:
            index=unresolved_usage_index(raw,image.registration['typesCount'],tag=1,source='conversion-opcodes.'+name,offset=at)
            _need(row.get('usageTag')==1 and row.get('registeredTypeIndex')==index and row.get('identity')==_CELL_TYPES[name]
                  and _type(image,index)==_CELL_TYPES[name],'named non-byref conversion class differs: '+name)
            pointer=image.pe.u64_at_va(_rva(image.registration['types'])+index*8)
            _need(image.pe.bytes_at_va(pointer,16).hex()==row.get('rawTypeHex'),'raw class record differs: '+name)
        else:
            word=int.from_bytes(raw,'little');tag=_OPAQUE_CELLS[name]
            _need(size==8 and row.get('usageTag')==tag and row.get('identityBoundary')=='encoded-only'
                  and word<=0xffffffff and word&1 and word>>29==tag,'opaque usage promoted/malformed: '+name)
    return result


def validate_conversion_opcode_rules(image: Any,spec: dict,body: bytes,body_rva: int,
                                      opcode_ids: dict[str,int],contract: dict,extents: dict[int,int]) -> dict:
    """Authenticate within an already gated image and authenticated Execute."""
    _claims(spec);_value_layout(image,contract);targets={}
    for role,identity in _METHODS.items():
        row=_ref(contract,_METHOD_REFS[role]) if role in _METHOD_REFS else spec['methods'][role]
        # Some inherited catalogs omit count/return labels. The named expected
        # signature still checks every actual carrier and flag in metadata.
        normalized=dict(row)
        if 'parameterCount' not in normalized: normalized['parameterCount']=len(identity[2])
        _need(type(normalized['parameterCount']) is int,'invalid method parameter count: '+role)
        for key,value in [('returnTypeName',identity[3]),('static',identity[4]),('generic',False)]:
            if key in row: _need(type(row[key]) is type(value) and row[key]==value,'declared method identity differs: '+role)
        targets[role]=_identity(image,normalized,identity,role,extents)
    for role in set(_HELPER_REFS)|set(spec['helpers']):
        row=_ref(contract,_HELPER_REFS[role]) if role in _HELPER_REFS else spec['helpers'][role]
        count=row['byteCount'];_need(type(count) is int and 0<count<=128,'invalid helper window: '+role)
        at=_rva(row['rva']);_hash(image.pe.bytes_at_va(image.pe.image_base+at,count),row,'helpers.'+role);targets[role]=at
        if role in spec['helpers']:
            expected='opaque-callee-request-only' if role=='overflowRequest' else 'finite-leaf-program'
            _need(row.get('effectBoundary')==expected,'helper outcome boundary differs: '+role)
    # These shared helper grammars are dependencies of terminating/cursor claims.
    _expect(image.pe.bytes_at_va(image.pe.image_base+targets['throwStop'],20),bytes.fromhex('4883ec2833c04889413848894140e87d030000cc'),'throwStop')
    _expect(image.pe.bytes_at_va(image.pe.image_base+targets['subtractSlot'],10),bytes.fromhex('4863c2482bc8488bc1c3'),'subtractSlot')
    _expect(image.pe.bytes_at_va(image.pe.image_base+targets['advancePointer'],7),bytes.fromhex('4863c24803c1c3'),'advancePointer')
    _expect(image.pe.bytes_at_va(image.pe.image_base+targets['doubleToLong'],6),bytes.fromhex('f2480f2cc0c3'),'doubleToLong')
    for role,path in _TAIL_REFS.items():
        row=_ref(contract,path);at=_rva(row['rva']);_hash(_slice(body,body_rva,at,row['byteCount'],role),row,role);targets[role]=at
    # RestorePc is immediately before the independently owned PC-advance tail.
    targets['restorePc']=targets['pcAdvance']-5
    _expect(_slice(body,body_rva,targets['restorePc'],5,'restorePc'),bytes.fromhex('be0c000000'),'restorePc')
    for role,shape in [('zeroRegister','4533ed'),('slotWidth','be0c000000')]:
        row=_ref(contract,'basicOpcodeRules.sharedWindows.'+role);at=_rva(row['rva'])
        raw=_slice(body,body_rva,at,row['byteCount'],role);_hash(raw,row,role);_expect(raw,bytes.fromhex(shape),role)
    cells=_cells(image,spec)
    for role,tokens in _LEAF_PROGRAMS.items():
        row=spec['methods'][role] if role in spec['methods'] else spec['helpers'][role]
        at=targets[role];expected=_program(tokens,at,targets,cells)
        _need(row['byteCount']==len(expected),'finite leaf extent differs: '+role)
        _expect(image.pe.bytes_at_va(image.pe.image_base+at,len(expected)),expected,'leaf.'+role)
    _need(spec['helpers']['overflowRequest']['byteCount']==5,'overflow request extent differs')
    opaque=spec['helpers']['overflowRequest'];at=targets['overflowRequest']
    _expect(image.pe.bytes_at_va(image.pe.image_base+at,5),_program((('branch','e9','overflowCallee'),),at,
            {'overflowCallee':_rva(opaque['jumpTargetRva'])},cells),'overflow request')
    targets.update({name:_rva(row['rva']) for name,row in spec['blocks'].items()})
    for name,row in spec['blocks'].items():
        at=targets[name];raw=_slice(body,body_rva,at,row['byteCount'],name);_hash(raw,row,name)
        expected=_program(_PROGRAMS[name],at,targets,cells)
        _expect(raw,expected,'conversion.'+name)
        _need(row.get('next')==_NEXT[name],'graph continuation differs: '+name)
        next_name=_NEXT[name]
        if next_name and _FALLTHROUGH[name]:
            _need(at+len(expected)==targets[next_name],'noncontiguous graph fallthrough: '+name)
    actual={r['name']:r['id'] for r in enum_members(image.metadata,field_defaults(image.metadata),'IFix.Core.Code')}
    _need(actual==opcode_ids,'Code enum layout differs')
    selected={name for name in actual if name.startswith('Conv_') and name!='Conv_I8'}
    _need(selected==set(spec['rules']),'remaining Code conversions differ')
    dispatch=contract['dispatchRules'];extensions=dispatch['extensions'];entries={_rva(r['entryRva']) for r in dispatch['entryPoints']}
    for name,row in spec['rules'].items():
        _need(row['opcodeId']==actual[name],'Code ID differs: '+name)
        entry=resolve_selected_dispatch_entry(body,body_rva,_rva(contract['basicOpcodeRules']['dispatchStartRva']),actual[name],
            zero_compare_rva=_rva(extensions['zeroCompare']['rva']),sub_esi_rva=_rva(extensions['subEsi']['rva']),entry_rvas=entries)
        _need(entry==targets[row['entryBlock']],'selected conversion entry differs: '+name)
    return dict(status='validated_conditional_conversion_opcode_rules',ruleCount=len(spec['rules']),finiteBlockCount=len(_PROGRAMS),
                finiteLeafCount=len(_LEAF_PROGRAMS),rules=project_conversion_opcode_rules(None,spec),
                evidenceBoundary='conditional',executionBoundary='unobserved',floatingBoundary=spec['floatingBoundary'],
                exceptionBoundary=spec['exceptionBoundary'],managedBoundary=spec['managedBoundary'])


def project_conversion_opcode_rules(instructions: list[dict]|None,spec: dict) -> list[dict]:
    """Project authored conversion rows only; no numeric/runtime evaluation."""
    _claims(spec);result=[]
    selected=[dict(opcode=name,**row) for name,row in spec['rules'].items()] if instructions is None else instructions
    for instruction in selected:
        name=instruction.get('opcode')
        if name not in spec['rules']:continue
        row=spec['rules'][name]
        _need(type(instruction.get('opcodeId')) is int and instruction['opcodeId']==row['opcodeId'],'authored opcode ID differs: '+name)
        if instructions is not None:
            operand=instruction.get('operand')
            _need(type(operand) is int and 0<=operand<=0xffffffff,'invalid authored Int32 operand: '+name)
            signed=operand if operand<0x80000000 else operand-0x100000000
            if 'operandSigned' in instruction:
                _need(type(instruction['operandSigned']) is int and instruction['operandSigned']==signed,'inconsistent signed operand: '+name)
        result.append(dict(opcode=name,opcodeId=row['opcodeId'],normalTopDelta=0,entryBlock=row['entryBlock'],
                           normalResultBoundary=row['normalResultBoundary'],floatingBoundary=row['floatBoundary'],
                           evidenceBoundary='conditional',executionBoundary='unobserved'))
    return result


def validate_selected_conversion_opcode_rules(contract: dict,*,gameassembly: Path|None,metadata: Path|None,spec: dict|None=None) -> dict:
    """Gate explicit selected inputs before opening an image or emitting rows."""
    if gameassembly is None or metadata is None:
        return dict(status='missing',detail='explicit GameAssembly.dll and metadata paths are required',rules=[])
    inputs=contract['nativeInputs'];gate=check_installed_native_inputs(inputs['gameAssemblySha256'],inputs['globalMetadataSha256'],
        gameassembly=Path(gameassembly),metadata=Path(metadata))
    if gate.status!='validated':return dict(status=gate.status,detail=gate.detail,rules=[])
    image=NativeImage(gate.gameassembly,gate.metadata,label='ifix.conversion-opcodes');extents=image.mapper.pdata_function_extents(image.pe)
    at=_identity(image,contract['consumer'],('IFix.Core.VirtualMachine','Execute',_EXECUTE_TYPES,'IFix.Core.Value*',False),'Execute',extents)
    body=image.pe.bytes_at_va(image.pe.image_base+at,contract['consumer']['bodyBytes'])
    ids={r['name']:r['id'] for r in enum_members(image.metadata,field_defaults(image.metadata),'IFix.Core.Code')}
    return validate_conversion_opcode_rules(image,spec if spec is not None else contract['conversionOpcodeRules'],body,at,ids,contract,extents)


